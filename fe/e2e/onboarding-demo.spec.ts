import { expect, test } from '@playwright/test';

test('the native lesson generates and revises only prerecorded browser data', async ({ page }) => {
  test.setTimeout(60_000);
  await page.setViewportSize({ width: 1440, height: 1000 });
  const api: string[] = []; const sockets: string[] = [];
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) api.push(request.url()); });
  page.on('websocket', socket => sockets.push(socket.url()));
  await page.route(url => url.pathname.startsWith('/api/'), route => route.abort());
  await page.addInitScript(() => { if (window.location.protocol !== 'data:') localStorage.setItem('demo-isolation-check', 'keep'); });
  await page.goto('/next/?demo=onboarding');
  await expect(page.getByRole('complementary', { name: '演示模式', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'New area', exact: true }).click();
  await page.getByRole('button', { name: '填入这个名字', exact: true }).click();
  await page.getByRole('button', { name: '下一步', exact: true }).click();
  await page.getByRole('button', { name: 'Default template: No template', exact: true }).click();
  await page.getByRole('menuitem', { name: /^Small change/ }).click();
  await page.getByRole('button', { name: '下一步', exact: true }).click();
  await page.getByRole('button', { name: '下一步', exact: true }).click();
  await page.getByRole('button', { name: 'Create area', exact: true }).click();
  await page.getByRole('button', { name: 'New track in 我的练习项目', exact: true }).click();
  await page.getByRole('button', { name: '填入练习需求', exact: true }).click();
  await expect(page.getByRole('button', { name: /^Track 作品集练习/ })).toHaveCount(0);
  await page.getByRole('button', { name: '下一步', exact: true }).click();
  await page.getByRole('button', { name: '下一步', exact: true }).click();
  await page.getByRole('button', { name: 'Create track', exact: true }).click();
  const preview = page.frameLocator('iframe[title="作品集演示"]');
  await expect(preview.getByRole('heading', { name: '我的作品集', exact: true })).toBeVisible();
  await expect(page.getByText('这里没有调用模型或运行验证', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Close conversation', exact: true }).click();
  await page.getByRole('button', { name: 'Open index.html', exact: true }).click();
  await expect(page.frameLocator('iframe[title="index.html"]').getByRole('heading', { name: '我的作品集', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Back to track', exact: true }).click();
  await page.getByRole('button', { name: '重新打开并继续', exact: true }).click();
  await page.getByRole('button', { name: '填入一次修改需求', exact: true }).click();
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await expect(preview.getByRole('heading', { name: '我的第一个作品', exact: true })).toBeVisible();
  expect(api).toEqual([]); expect(sockets).toEqual([]);
  expect(await page.evaluate(() => Object.fromEntries(Object.entries(localStorage)))).toEqual({ 'demo-isolation-check': 'keep' });
  await page.reload();
  await expect(page.getByRole('complementary', { name: '演示模式', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: /^Collapse area 我的练习项目/ })).toHaveCount(0);
  expect(api).toEqual([]); expect(sockets).toEqual([]);
  await page.getByRole('button', { name: '重新开始', exact: true }).click();
  await expect(page.getByRole('button', { name: 'New area', exact: true })).toBeVisible();
  expect(api).toEqual([]);
});

test('the Demo banner and callout remain usable on a phone', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const api: string[] = [];
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) api.push(request.url()); });
  await page.route(url => url.pathname.startsWith('/api/'), route => route.abort());
  await page.goto('/next/?demo=onboarding');
  await expect(page.getByRole('complementary', { name: '演示模式' })).toBeVisible();
  await expect(page.getByRole('note', { name: '先做出一个能预览的小作品' })).toBeVisible();
  await page.getByRole('button', { name: 'New area', exact: true }).click();
  const fill = page.getByRole('button', { name: '填入这个名字', exact: true });
  await expect(fill).toBeVisible();
  const box = await fill.boundingBox();
  expect(box?.x).toBeGreaterThanOrEqual(0);
  expect((box?.x ?? 0) + (box?.width ?? 0)).toBeLessThanOrEqual(390);
  await fill.click();
  await expect(page.getByRole('textbox', { name: 'Name', exact: true })).toHaveValue('我的练习项目');
  expect(api).toEqual([]);
});
