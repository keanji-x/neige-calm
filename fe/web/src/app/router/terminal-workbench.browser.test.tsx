it.each([false, true])('resizes the independent terminal entry and preserves Chat width after Chat closes with reduced motion %s', async reduced => {
  await page.viewport(1512, 950);
  const { sockets, Socket } = workbenchSockets(); vi.stubGlobal('WebSocket', Socket);
  setupWorkbench({ cards: [{ ...terminalCard('resize'), payload: { terminal_id: 'pty-1' } }] });
  await page.getByRole('button', { name: /^resize/ }).click();
  await waitFor(() => expect(sockets).toHaveLength(1));
  act(() => sockets[0].open());
  const terminal = document.querySelector<HTMLElement>('[data-nc-terminal-workbench]')!;
  const width = () => terminal.getBoundingClientRect().width;
  const edge = page.getByRole('separator', { name: 'Resize conversation' });
  await expect.element(edge).toBeVisible();
  expect(document.querySelectorAll('[role="separator"][aria-label="Resize conversation"]')).toHaveLength(1);
  (edge.element() as HTMLElement).focus();
  await userEvent.keyboard('{Home}');
  await commands.emulateReducedMotion(reduced);
  const before = width();
  for (const [key, delta] of [['ArrowLeft', 16], ['ArrowLeft', 32], ['ArrowRight', 16]] as const) {
    await userEvent.keyboard(`{${key}}`);
    expect(width()).toBeCloseTo(before + delta, 0);
  }
  await userEvent.keyboard('{Home}');
  expect(width()).toBeCloseTo(before, 0);
  const box = edge.element().getBoundingClientRect();
  const main = terminal.closest('main')!;
  const region = main.getBoundingClientRect();
  await userEvent.dragAndDrop(edge.element(), main, {
    sourcePosition: { x: box.width / 2, y: box.height / 2 },
    targetPosition: { x: box.left + box.width / 2 - 96 - region.left, y: box.top + box.height / 2 - region.top },
    force: true, steps: 6,
  });
  await expect.poll(width).toBeCloseTo(before + 96, 0);
  await page.getByRole('button', { name: 'Hide terminal' }).click();
  await page.getByRole('button', { name: 'Conversation Main discussion' }).click();
  const chat = page.getByRole('complementary', { name: 'Main discussion' });
  await expect.poll(() => chat.element().getAnimations().length).toBe(0);
  (edge.element() as HTMLElement).focus();
  const field = chat.getByRole('combobox', { name: 'Message' });
  await field.fill('/terminal'); await field.click(); await userEvent.keyboard('{Enter}');
  (edge.element() as HTMLElement).focus();
  const shared = width();
  await userEvent.keyboard('{ArrowLeft}');
  await expect.poll(width).toBeCloseTo(shared + 16, 0);
  expect(chat.element().getBoundingClientRect().width).toBeCloseTo(width(), 0);
  const resized = width();
  await chat.getByRole('button', { name: 'Close conversation' }).click();
  await waitFor(() => expect(screen.queryByRole('complementary', { name: 'Main discussion' })).toBeNull());
  expect(width()).toBeCloseTo(resized, 0);
  expect(document.querySelectorAll('[role="separator"][aria-label="Resize conversation"]')).toHaveLength(1);
  await page.getByRole('button', { name: 'Hide terminal' }).click();
  expect(screen.queryByRole('separator', { name: 'Resize conversation' })).toBeNull();
  expect(document.querySelector('[data-nc-drawer-resizable]')).toBeNull();
  expect(sockets[0].readyState).toBe(1);
});

