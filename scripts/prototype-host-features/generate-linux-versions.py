#!/usr/bin/env python3
"""Print syscall introduction metadata from upstream x86-64 release sources.

Run explicitly to regenerate linux-versions.tsv. The Cargo scanner is offline.
The scan is bounded to v5.0 through v5.11 for the prototype's known capabilities.
"""

from concurrent.futures import ThreadPoolExecutor
from urllib.request import urlopen


UPSTREAM = "https://raw.githubusercontent.com/torvalds/linux"
TABLE = "arch/x86/entry/syscalls/syscall_64.tbl"
CLOSE_RANGE_HEADER = "include/uapi/linux/close_range.h"
SYSCALLS = {
    "pidfd_open": "pidfd-open",
    "openat2": "openat2",
    "close_range": "close-range",
}
CLOEXEC = "close-range-cloexec"


def read(tag, path):
    with urlopen(f"{UPSTREAM}/{tag}/{path}", timeout=20) as response:
        return response.read().decode()


def capabilities(minor):
    tag = f"v5.{minor}"
    names = set()
    for line in read(tag, TABLE).splitlines():
        fields = line.split()
        if len(fields) >= 4 and fields[0].isdigit() and fields[1] in ("64", "common"):
            names.add(fields[2])
    if not {"read", "write", "close"} <= names:
        raise ValueError(f"unexpected x86-64 syscall table in {tag}")
    found = {capability: TABLE for name, capability in SYSCALLS.items() if name in names}
    if "close_range" in names:
        for line in read(tag, CLOSE_RANGE_HEADER).splitlines():
            if line.split()[:2] == ["#define", "CLOSE_RANGE_CLOEXEC"]:
                found[CLOEXEC] = CLOSE_RANGE_HEADER
                break
    return tag, found


def main():
    first = {}
    with ThreadPoolExecutor(max_workers=4) as pool:
        for minor, (tag, found) in enumerate(pool.map(capabilities, range(12))):
            if minor == 0 and found:
                raise ValueError("a capability is present at the lower bound")
            for name, path in found.items():
                first.setdefault(name, (tag.removeprefix("v"), f"{UPSTREAM}/{tag}/{path}"))
    if set(first) != {*SYSCALLS.values(), CLOEXEC}:
        raise ValueError("a capability was not found in the scanned release range")

    print("# Generated by generate-linux-versions.py from upstream Linux x86-64 release tags")
    for name, (version, source) in sorted(first.items()):
        print(f"{name}\t{version}\t{source}")


if __name__ == "__main__":
    main()
